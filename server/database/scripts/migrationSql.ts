import { mkdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'

import { migrationsFor } from '#server/database/migrations/index.ts'
import { EXTERNAL_SCHEMA } from '#server/database/targets.ts'

/** Supabase names migrations by timestamp; these are fixed, so the files keep their names. */
const SUPABASE_DATE = '20261113'

/** Every Supabase migration file's path and text. */
export function migrationFiles(): Record<string, string> {
    const files: Record<string, string> = {}

    for (const migration of migrationsFor('postgres')) {
        const slug = migration.name.replace(/ /g, '_')
        const number = String(migration.version).padStart(4, '0')

        const body = [
            `-- Kynova migration ${migration.version}: ${migration.name}`,
            `-- Generated by \`npm run db:sql\` from server/database/migrations/postgres/${number}_${slug}.sql.`,
            '-- Edit that file, not this one.',
            '',
            `CREATE SCHEMA IF NOT EXISTS ${EXTERNAL_SCHEMA};`,
            `SET search_path TO ${EXTERNAL_SCHEMA};`,
            '',
            'CREATE TABLE IF NOT EXISTS schema_migrations (',
            '  version    INTEGER PRIMARY KEY,',
            '  name       TEXT NOT NULL,',
            '  applied_at BIGINT NOT NULL',
            ');',
            '',
            migration.sql.trim(),
            '',
            `INSERT INTO schema_migrations (version, name, applied_at)`,
            `VALUES (${migration.version}, '${migration.name.replace(/'/g, "''")}', (extract(epoch FROM now()) * 1000)::bigint)`,
            'ON CONFLICT (version) DO NOTHING;',
            '',
        ].join('\n')

        const file = `${SUPABASE_DATE}${String(migration.version).padStart(6, '0')}_kynova_${slug}.sql`

        files[path.join('server', 'database', 'migrations', 'supabase', file)] = body
    }

    return files
}

if (import.meta.main) {
    for (const [file, content] of Object.entries(migrationFiles())) {
        mkdirSync(path.dirname(file), { recursive: true })
        writeFileSync(file, content)
        console.log(`Wrote ${file}`)
    }
}
